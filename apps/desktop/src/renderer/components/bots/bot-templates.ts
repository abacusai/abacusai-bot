/**
 * Prebuilt bot roles: a starting point, not a cage. Picking one prefills the
 * creation dialog and everything stays editable before Create. Card copy is
 * localized; persona and mission are not, because they are the prompt the
 * agent runs on and the user rewrites them in the dialog. A template can sit
 * in more than one category; it is one template either way.
 */

export type BotTemplateCategory =
  | "featured"
  | "personal-assistant"
  | "productivity"
  | "social-media"
  | "research"
  | "finance"
  | "marketing"
  | "recruiting";

