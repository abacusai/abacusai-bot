/** Ids in a category, in the sheet's order. */
export const templateIdsInCategory = (
  category: BotTemplateCategory
): string[] =>
  BOT_TEMPLATES.filter((template) =>
    template.categories.includes(category)
  ).map((template) => template.id);

/** The Featured tab's ids, in the sheet's order. */
export const FEATURED_TEMPLATE_IDS: readonly string[] =
  templateIdsInCategory("featured");

/**
 * Connected first, in the order given, but only when that bot belongs to the
 * tab: the Finance tab does not grow a WhatsApp card because WhatsApp is
 * linked. The rest follow in the sheet's order; no card repeats. Ids only, so
 * the ordering rule is testable without a bot or a connector.
 */
export const orderedTemplateIds = (
  category: BotTemplateCategory,
  connectors: readonly string[] = []
): string[] => {
  const members = templateIdsInCategory(category);
  const leading = connectors
    .map((connector) => TEMPLATE_FOR_CONNECTOR[connector])
    .filter((id): id is string => id != null && members.includes(id));

  return [...new Set([...leading, ...members])];
};

/** The Featured tab's order — what a fresh Create Bot page leads with. */
export const heroTemplateIds = (connectors: readonly string[] = []): string[] =>
  orderedTemplateIds("featured", connectors);
