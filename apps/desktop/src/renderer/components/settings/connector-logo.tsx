/**
 * Draws a connector's logo. The colour rides two custom properties rather than
 * a class per brand: Tailwind only emits utilities spelled out in the source.
 */

export const ConnectorLogo = ({
  connector,
}: {
  connector: ConnectorDefinition;
}): JSX.Element => {
  const asset = connector.logo != null ? LOGO_ASSETS[connector.logo] : null;
  if (asset != null) {
    return (
      <img
        src={asset}
        alt=""
        className="h-6 w-6 object-contain"
        draggable={false}
      />
    );
  }

  const mark = CONNECTOR_MARKS[connector.id];
  if (mark == null) {
    return <Plug className="text-primary size-3.5" />;
  }

  const tone = "text-(--mark) dark:text-(--mark-dark)";
  // Cast because React's CSSProperties has no slot for custom properties, and
  // FontAwesome's own style prop narrows further still.
  const style = {
    "--mark": mark.light,
    "--mark-dark": mark.dark ?? mark.light,
  } as CSSProperties & Record<`--${string}`, string>;

  if (mark.icon != null) {
    const MarkIcon = mark.icon;
    return <MarkIcon className={`${tone} size-3.5`} style={style} />;
  }

  if (mark.monogram != null) {
    return (
      <span
        className={`${tone} text-xs leading-none font-semibold`}
        style={style}
      >
        {mark.monogram}
      </span>
    );
  }

  return (
    <svg
      viewBox={mark.viewBox ?? "0 0 24 24"}
      fill="currentColor"
      fillRule={mark.evenOdd === true ? "evenodd" : undefined}
      aria-hidden="true"
      className={`h-5 w-5 ${tone}`}
      style={style}
    >
      <path d={mark.path} />
    </svg>
  );
};
