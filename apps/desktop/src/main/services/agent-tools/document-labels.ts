/** "tr-TR", "TR", "pt_BR" → "tr", "tr", "pt"; anything unreadable → "en". */
export const languageOf = (value: unknown): string => {
  const code = typeof value === "string" ? value.trim() : "";
  return /^[a-z]{2,3}([-_][a-z0-9]{2,8})*$/i.test(code)
    ? code.replace("_", "-")
    : "en";
};

export const labelsFor = (language: string): Labels =>
  TABLE[languageOf(language).split("-")[0]!.toLowerCase()] ?? en;

/** A currency as written ("£", "TL", "usd") as an ISO code, when there is one. */
const ISO: Record<string, string> = {
  $: "USD",
  US$: "USD",
  "€": "EUR",
  "£": "GBP",
  "₺": "TRY",
  TL: "TRY",
  "₹": "INR",
  RS: "INR",
  "¥": "JPY",
  "￥": "CNY",
  RMB: "CNY",
  "₩": "KRW",
  RP: "IDR",
  R$: "BRL",
  ZŁ: "PLN",
  ZL: "PLN",
  CHF: "CHF",
};

const isoOf = (currency: string): string | null => {
  const key = currency.trim().toUpperCase();
  if (ISO[key] != null) return ISO[key]!;
  if (/^[A-Z]{3}$/.test(key)) {
    try {
      new Intl.NumberFormat("en", { style: "currency", currency: key });
      return key;
    } catch {
      return null;
    }
  }
  return null;
};

/** The language as Intl reads it, or English when Intl does not know it. */
const localeOf = (language: string): string => {
  const code = languageOf(language);
  try {
    return Intl.NumberFormat.supportedLocalesOf(code).length > 0
      ? code
      : "en-GB";
  } catch {
    return "en-GB";
  }
};

/**
 * A sum in the document's language: "29.400,00 ₺" in Turkish, "29.400,00 €"
 * in German, "£29,400.00" in English. Turkish business writing puts the lira
 * sign after the figure, which Intl does not, so Turkish is set by hand.
 */
export const formatMoney = (
  amount: number,
  currency: string,
  language: string
): string => {
  const locale = localeOf(language);
  const iso = isoOf(currency);
  const figure = (value: number): string =>
    new Intl.NumberFormat(locale, {
      minimumFractionDigits: 2,
      maximumFractionDigits: 2,
    }).format(value);
  const sign = amount < 0 ? "−" : "";
  const plain = figure(Math.abs(amount));

  if (currency.trim().length === 0) return `${sign}${plain}`;
  if (iso == null || locale.toLowerCase().startsWith("tr")) {
    const symbol = iso === "TRY" ? "₺" : currency.trim();
    return locale.toLowerCase().startsWith("tr")
      ? `${sign}${plain}\u00a0${symbol}`
      : symbol.length === 1
        ? `${sign}${symbol}${plain}`
        : `${sign}${symbol} ${plain}`;
  }

  return new Intl.NumberFormat(locale, {
    style: "currency",
    currency: iso,
    currencyDisplay: "narrowSymbol",
  })
    .format(amount)
    .replace("-", "−");
};

/** A plain figure (a change, a total of hours) in the document's language. */
export const formatNumber = (value: number, language: string): string =>
  new Intl.NumberFormat(localeOf(language), {
    maximumFractionDigits: 2,
  }).format(value);

/** A percentage as the language writes it: "20%" in English, "%20" in Turkish. */
export const formatPercent = (value: number, language: string): string =>
  new Intl.NumberFormat(localeOf(language), {
    style: "percent",
    maximumFractionDigits: 2,
  }).format(value / 100);
